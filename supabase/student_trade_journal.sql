-- FrancoTrades Mentoria — Diário de Trade privado dos mentorados
-- Execute UMA VEZ no SQL Editor do Supabase.
--
-- Objetivos:
-- 1) Cada mentorado ativo acessa somente as próprias contas, trades, prints e comentários do mentor.
-- 2) Administradores acessam todos os mentorados, inclusive após expiração/inativação.
-- 3) O histórico NÃO é apagado quando o acesso do aluno termina.
-- 4) O diário pessoal do administrador não é armazenado nestas tabelas.

create or replace function public.has_active_mentorship_access(
  target_user uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = target_user
      and p.role = 'aluno'
      and p.status = 'ativo'
      and (
        p.data_expiracao is null
        or p.data_expiracao >= current_date
      )
  );
$$;

create or replace function public.can_access_student_trade_journal(
  target_student uuid
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    public.is_admin()
    or (
      auth.uid() = target_student
      and public.has_active_mentorship_access(target_student)
    );
$$;


create table if not exists public.student_trade_accounts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id),
  name text not null,
  broker text,
  account_type text not null default 'personal'
    check (account_type in ('personal','prop','simulator')),
  prop_firm text,
  currency text not null default 'USD'
    check (currency in ('USD','BRL')),
  starting_balance numeric(18,2) not null default 0,
  account_size numeric(18,2),
  account_stage text not null default 'new'
    check (account_stage in ('new','existing')),
  current_balance numeric(18,2),
  drawdown_remaining numeric(18,2),
  max_drawdown numeric(18,2),
  profit_target numeric(18,2),
  daily_loss_limit numeric(18,2),
  consistency_rule numeric(8,2),
  rules jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists student_trade_accounts_student_idx
  on public.student_trade_accounts(student_id, active, created_at desc);

alter table public.student_trade_accounts enable row level security;

drop policy if exists "Trade accounts private access" on public.student_trade_accounts;
create policy "Trade accounts private access"
on public.student_trade_accounts
for select
to authenticated
using (public.can_access_student_trade_journal(student_id));

drop policy if exists "Trade accounts private insert" on public.student_trade_accounts;
create policy "Trade accounts private insert"
on public.student_trade_accounts
for insert
to authenticated
with check (
  public.can_access_student_trade_journal(student_id)
  and (
    public.is_admin()
    or student_id = auth.uid()
  )
);

drop policy if exists "Trade accounts private update" on public.student_trade_accounts;
create policy "Trade accounts private update"
on public.student_trade_accounts
for update
to authenticated
using (public.can_access_student_trade_journal(student_id))
with check (
  public.can_access_student_trade_journal(student_id)
  and (
    public.is_admin()
    or student_id = auth.uid()
  )
);


create table if not exists public.student_trades (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id),
  account_id bigint references public.student_trade_accounts(id) on delete set null,
  trade_date date not null,
  symbol text not null,
  side text not null default 'long'
    check (side in ('long','short')),
  quantity numeric(18,4),
  entry_price numeric(18,6),
  exit_price numeric(18,6),
  pnl numeric(18,2) not null default 0,
  fees numeric(18,2) not null default 0,
  setup text,
  emotion text,
  rr numeric(12,4),
  mfe numeric(18,2),
  mae numeric(18,2),
  grade integer check (grade is null or (grade between 1 and 5)),
  notes text,
  source text not null default 'manual'
    check (source in ('manual','csv','thinkorswim','tradeify','other')),
  external_id text,
  raw_data jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists student_trades_student_date_idx
