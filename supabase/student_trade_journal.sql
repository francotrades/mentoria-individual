create or replace function public.set_student_trade_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_student_trade_accounts_updated_at
  on public.student_trade_accounts;
create trigger set_student_trade_accounts_updated_at
before update on public.student_trade_accounts
for each row execute function public.set_student_trade_updated_at();

